"""Writes the font block build.sh inlines into the panel pages:

    web/fonts.css     Barlow Condensed (OFL, third_party/barlow), Latin subset

Needs fontTools: python3 assets/render_web_theme.py
"""

import base64
import io
import os

from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Basic Latin, Latin-1 and the punctuation the panel and game titles use; other
# characters fall back to the system font.
UNICODES = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193]
NOTE = "/* Generated by assets/render_web_theme.py */\n"


def data_uri(mime, data):
    return f"data:{mime};base64,{base64.b64encode(data).decode()}"


def face(name, weight):
    options = subset.Options(flavor="woff", layout_features=["kern", "tnum"], name_IDs=[0, 1, 2, 13, 14], hinting=False, desubroutinize=True)
    font = subset.load_font(os.path.join(ROOT, "third_party", "barlow", name), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)
    out = io.BytesIO()
    subset.save_font(font, out, options)
    return (f'@font-face{{font-family:"Barlow Condensed";font-weight:{weight};font-display:swap;'
            f'src:url({data_uri("font/woff", out.getvalue())}) format("woff")}}\n')


def write(name, text):
    with open(os.path.join(ROOT, "web", name), "w", encoding="utf-8") as out:
        out.write(NOTE + text)
    print(f"web/{name}: {len(text) // 1024} KB")


def main():
    write("fonts.css", "/* Barlow Condensed, Copyright 2017 The Barlow Project Authors, SIL OFL 1.1 */\n"
          + face("BarlowCondensed-Medium.ttf", 500) + face("BarlowCondensed-Bold.ttf", 700))


if __name__ == "__main__":
    main()
